"""Does debate round 3 add anything over round 2? (pre-check for the lean experiment, the maintainer's planning note "Lean new experiment").

Offline, $0. Data: the existing debates under the default flags (P2_DATA=uncapped, paper-1 answer rule P2_ANSWER_RULE=p1):
  * mixed: six-model debate, items complete in rounds 0..3 (operators/debate.py `full`, the core 225), fixed agent order;
  * copies: six DeepSeek V3.2 copies, arms plain / selfonly / pressure, each on its complete items;
  * weak: W = DeepSeek, GLM, Mistral, Haiku on the chosen items (contested + all-W-wrong + control), complete in rounds 0..3.
Plurality = paper-1 answer identity, ties to the first row in the fixed order, truncated row = missing vote (as the operators).
Per step t-1 -> t: gain, paired bootstrap 95% CI over items (10,000 resamples, random.Random(0)), W/L (fixed / broken),
exact two-sided McNemar for r3 vs r2 (and each step). Share of r3-r0 gain reached by r2.
Tokens: mean output tokens per call per round; $ per item per round = sum over agents of pi_in*t_in + pi_out*t_out with
datasets/model-prices ALL rows (Claude at LIST price). Weak rows store no t_in: their $ uses output tokens only (input
omitted, flagged). Round 0 is the stored matrix / T=1 draws (shared with other methods); "debate cost" = rounds 1..3.
Output: summaries/out2/debate_rounds.md (+ .json).
"""
import json, random, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "operators"))
from p2parts import tn5 as IO          # noqa: E402
from p2parts import budget as BIO      # noqa: E402
import debate_weak as DW               # noqa: E402

PR = BIO.prices()


def price_key(agent):
    a = agent.split("#")[0]
    return {"claude:haiku": "claude_haiku", "claude:sonnet55": "claude_sonnet55"}.get(a, a.replace("/", "_"))


def cost(agent, r):
    t = r.get("tok") or {}
    tin = t.get("in") if t else None
    tout = (t.get("out") if t else None) or r.get("tok_out") or 0
    pi, po = PR[price_key(agent)]
    return (tin or 0) * pi + tout * po, tout, tin is None


def boot_ci(d, B=10000, seed=0):
    rng = random.Random(seed); n = len(d); m = []
    for _ in range(B):
        m.append(sum(d[rng.randrange(n)] for _ in range(n)) / n)
    m.sort(); return m[int(0.025 * B)], m[int(0.975 * B) - 1]


def analyse(name, ids, rows, agents, maj):
    """rows(i, a, rd) -> row; maj(list_of_rows) -> bool."""
    acc = {rd: [int(maj([rows(i, a, rd) for a in agents])) for i in ids] for rd in range(4)}
    n = len(ids); res = {"name": name, "items": n, "acc": {rd: sum(v) / n for rd, v in acc.items()}, "steps": {}}
    for rd in (1, 2, 3):
        d = [acc[rd][j] - acc[rd - 1][j] for j in range(n)]
        w = sum(x == 1 for x in d); l = sum(x == -1 for x in d)
        res["steps"][f"r{rd}-r{rd-1}"] = {"gain": sum(d) / n, "ci": boot_ci(d), "W": w, "L": l, "mcnemar_p": IO.mcnemar(w, l)}
    tot = res["acc"][3] - res["acc"][0]
    res["share_by_r2"] = (res["acc"][2] - res["acc"][0]) / tot if tot else None
    tok, usd, nmiss, nrow = {}, {}, 0, 0
    for rd in range(4):
        ts, cs = [], 0.0
        for i in ids:
            for a in agents:
                r = rows(i, a, rd)
                if not r: continue
                c, t, m = cost(a, r); ts.append(t); cs += c
                if rd > 0: nrow += 1; nmiss += m
        tok[rd] = sum(ts) / len(ts) if ts else None; usd[rd] = cs / n
    res["tok_out_mean"] = tok; res["usd_per_item"] = usd; res["input_missing"] = nmiss / max(nrow, 1) > 0.5
    deb = usd[1] + usd[2] + usd[3]
    res["save_drop_r3_debate"] = usd[3] / deb if deb else None
    res["save_drop_r3_incl_r0"] = usd[3] / (deb + usd[0]) if usd[0] else None
    return res


def main():
    out = []
    A = IO.DEBATE_AGENTS
    items = IO.load_debate(); full = {i: d for i, d in items.items() if all((a, rd) in d for a in A for rd in range(4))}
    out.append(analyse("mixed (6 models)", sorted(full), lambda i, a, rd: full[i][(a, rd)], A, IO.maj_correct))
    C = [f"deepseek/deepseek-v3.2#{k}" for k in range(6)]
    for arm in IO.ARMS:
        it = IO.load_homo(arm)
        f = {i: d for i, d in it.items() if all((a, rd) in d for a in C for rd in range(4))}
        out.append(analyse(f"copies DeepSeek x6, {arm}", sorted(f), lambda i, a, rd, f=f: f[i][(a, rd)], C, IO.maj_correct))
    _, chosen, R0 = DW._data(); _, wf = DW._load_debate(chosen, R0)
    W = DW.W
    out.append(analyse("weak pool W (4)", sorted(wf), lambda i, a, rd: wf[i][(a, rd)], W,
                       lambda rs: DW.plur(dict(zip(W, rs)), "first", W) == 1.0))
    od = ROOT / "summaries" / "out2"
    (od / "debate_rounds.json").write_text(json.dumps(out, indent=1, default=str))
    pp = lambda x: f"{100 * x:+.1f}"
    L = ["# Debate: does round 3 add anything over round 2?", "",
         "Generated by `summaries/debate_rounds.py` (offline, $0). Uncapped data, paper-1 answer rule, ties to first in fixed order, "
         "truncated = missing vote. CI = paired bootstrap 95 % over items (10,000, seed 0); p = exact McNemar. "
         "$ = datasets/model-prices (Claude at list price). Debate cost = rounds 1-3; round 0 is the stored matrix/draws.", ""]
    L += ["| debate | n | r0 | r1 | r2 | r3 | r1−r0 [CI] W/L | r2−r1 [CI] W/L | r3−r2 [CI] W/L, p | share of r3−r0 by r2 |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in out:
        s = r["steps"]; cells = []
        for k in ("r1-r0", "r2-r1", "r3-r2"):
            x = s[k]; c = f"{pp(x['gain'])} [{pp(x['ci'][0])}, {pp(x['ci'][1])}] {x['W']}/{x['L']}"
            if k == "r3-r2": c += f", p={x['mcnemar_p']:.2f}"
            cells.append(c)
        sh = "n/a" if r["share_by_r2"] is None else f"{100 * r['share_by_r2']:.0f} %"
        L.append(f"| {r['name']} | {r['items']} | " + " | ".join(f"{100 * r['acc'][k]:.1f}" for k in range(4)) + " | " + " | ".join(cells) + f" | {sh} |")
    L += ["", "Gains in percentage points. Share > 100 % = round 3 lost accuracy; n/a = no r3−r0 gain.", "",
          "| debate | mean out tok/call r0 / r1 / r2 / r3 | $/item r0 / r1 / r2 / r3 | dropping r3 saves (of rounds 1-3) | (of rounds 0-3) |", "|---|---|---|---|---|"]
    for r in out:
        t = r["tok_out_mean"]; u = r["usd_per_item"]
        ft = lambda v: "–" if v is None else f"{v:,.0f}"
        L.append(f"| {r['name']}{' (input tokens not stored: $ output-only)' if r['input_missing'] else ''} | " + " / ".join(ft(t[k]) for k in range(4)) +
                 " | " + " / ".join(f"{u[k]:.4f}" for k in range(4)) + f" | {100 * r['save_drop_r3_debate']:.0f} % | " +
                 ("–" if r["save_drop_r3_incl_r0"] is None else f"{100 * r['save_drop_r3_incl_r0']:.0f} %") + " |")
    L += ["", "## Verdict", ""]
    for r in out:
        x = r["steps"]["r3-r2"]
        L.append(f"- {r['name']}: round 3 adds {pp(x['gain'])} pts [{pp(x['ci'][0])}, {pp(x['ci'][1])}] (W/L {x['W']}/{x['L']}, p = {x['mcnemar_p']:.2f}); "
                 f"dropping it saves {100 * r['save_drop_r3_debate']:.0f} % of debate cost (rounds 1-3).")
    (od / "debate_rounds.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
