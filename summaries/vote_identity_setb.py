"""Set B: votes with 'soft' identity (all correct=1 answers of an item = one group) vs old (code). Offline, $0.
python3 summaries/vote_identity_setb.py -> summaries/out2/vote_identity_setb.{md,json}"""
import csv, json, sys, collections
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "lib"))
from p1stats.tests_stats import mcnemar_exact
D = ROOT / "datasets/set_b"
POOL = ["claude-haiku-4-5", "claude-sonnet-4-6", "claude-opus-4-6", "deepseek/deepseek-v3.2", "z-ai/glm-4.7-flash",
        "qwen/qwen3.8-27b", "moonshotai/kimi-k2.5"]
DS, GLM, OPUS = POOL[3], POOL[4], POOL[2]
IDS = [r["id"] for r in csv.DictReader(open(D / "items.csv"))]
A = {}
for r in csv.DictReader(open(D / "answers.csv")):
    r["correct"] = int(r["correct"]); A[(r["id"], r["op"], r["model"], int(r["slot"]), int(r["round"]))] = r
get = lambda i, op, m, s=1, k=0: A.get((i, op, m, s, k))
ok = lambda r: r["correct"] if r else 0
code = lambda r: r["code"] if r else ""


def plur(keys, oks):  # same as SB.plurality_codes
    cnt, first = collections.Counter(), {}
    for j, c in enumerate(keys):
        if c:
            cnt[c] += 1; first.setdefault(c, j)
    if not cnt:
        return 0
    top = min(cnt, key=lambda c: (-cnt[c], first[c]))
    return int(any(o for c, o in zip(keys, oks) if c == top))


def vote_old(rs): return plur([code(r) for r in rs], [ok(r) for r in rs])


def vote_new(rs):
    keys = [("__OK__" if ok(r) else code(r)) if (ok(r) or code(r)) else "" for r in rs]
    return plur(keys, [ok(r) for r in rs])


res, vecs = {}, {}


def add(name, fn):
    o = [fn(i, vote_old) for i in IDS]; n = [fn(i, vote_new) for i in IDS]
    vecs[name] = (o, n)
    res[name] = {"acc_old": sum(o) / len(o), "acc_new": sum(n) / len(n),
                 "0to1": [i for i, a, b in zip(IDS, o, n) if (a, b) == (0, 1)],
                 "1to0": [i for i, a, b in zip(IDS, o, n) if (a, b) == (1, 0)]}


add("vote7_r0", lambda i, v: v([get(i, "draw", m) for m in POOL]))


def deb(i, v):
    r2 = [get(i, "debate7", m, 1, 2) for m in POOL]
    return v(r2) if all(r2) else v([get(i, "draw", m) for m in POOL])


add("debate7_r2", deb)
for m, nm in ((DS, "sc_deepseek"), (GLM, "sc_glm")):
    add(nm, lambda i, v, m=m: v([get(i, "draw", m, k) for k in range(1, 6)]))


def cop(i, v):
    r2 = [get(i, "copies", DS, k, 2) for k in range(1, 6)]
    return v(r2) if all(r2) else v([get(i, "draw", DS, k) for k in range(1, 6)])


add("copies_deepseek", cop)


def cmp(a, b):
    w = sum(1 for x, y in zip(a, b) if x == 0 and y == 1); l = sum(1 for x, y in zip(a, b) if x == 1 and y == 0)
    return {"acc_base": sum(a) / len(a), "acc_op": sum(b) / len(b), "delta": (sum(b) - sum(a)) / len(a), "W": w, "L": l, "p": mcnemar_exact(w, l)}


synth = [ok(get(i, "synth", OPUS)) for i in IDS]
first_ds = [ok(get(i, "draw", DS)) for i in IDS]; first_glm = [ok(get(i, "draw", GLM)) for i in IDS]
v7o, v7n = vecs["vote7_r0"]
D_ = {}
for tag, k in (("old", 0), ("new", 1)):
    D_[tag] = {
        "debate7_vs_vote7": cmp(v7o if k == 0 else v7n, vecs["debate7_r2"][k]),
        "synth_vs_vote7": cmp(v7o if k == 0 else v7n, synth),
        "sc_deepseek_vs_draw1": cmp(first_ds, vecs["sc_deepseek"][k]),
        "sc_glm_vs_draw1": cmp(first_glm, vecs["sc_glm"][k]),
        "copies_vs_sc5": cmp(vecs["sc_deepseek"][k], vecs["copies_deepseek"][k]),
    }
allok = [i for i in IDS if all(ok(get(i, "draw", m)) for m in POOL)]
multi = [i for i in allok if len({code(get(i, "draw", m)) for m in POOL}) > 1]
byitem = collections.defaultdict(list)
for k, r in A.items():
    byitem[k[0]].append(r)
clash = [i for i, rows in byitem.items()
         if {r["code"] for r in rows if r["correct"] and r["code"]} & {r["code"] for r in rows if not r["correct"] and r["code"]}]
out = {"votes": res, "deltas": D_, "all7_correct": len(allok), "all7_correct_multi_code": len(multi), "multi_ids": multi,
       "items_correct_and_wrong_share_code": clash}
json.dump(out, open(ROOT / "summaries/out2/vote_identity_setb.json", "w"), indent=1)
L = ["# Set B: voting identity, old (code) vs soft (all correct=1 = one group)", "",
     "Generated by `summaries/vote_identity_setb.py`. Tie rule and pool order as in operators/setb_report.py.", "",
     "| operator | acc old | acc new | 0→1 | 1→0 | ids |", "|---|---|---|---|---|---|"]
for k, v in res.items():
    L.append(f"| {k} | {v['acc_old']:.3f} | {v['acc_new']:.3f} | {len(v['0to1'])} | {len(v['1to0'])} | +{', '.join(v['0to1']) or '-'}; -{', '.join(v['1to0']) or '-'} |")
L += ["", "| comparison | identity | base → op | Δ | W / L | McNemar p |", "|---|---|---|---|---|---|"]
for c in D_["old"]:
    for tag in ("old", "new"):
        x = D_[tag][c]; L.append(f"| {c} | {tag} | {x['acc_base']:.3f} → {x['acc_op']:.3f} | {x['delta']:+.3f} | {x['W']} / {x['L']} | {x['p']:.3g} |")
L += ["", f"Items with all 7 first answers correct: {len(allok)}; with more than one code: {len(multi)}; one code: {len(allok)-len(multi)}.",
      f"Items where a correct and an incorrect answer share a code (any op): {len(clash)}."]
open(ROOT / "summaries/out2/vote_identity_setb.md", "w").write("\n".join(L) + "\n")
print("\n".join(L))
